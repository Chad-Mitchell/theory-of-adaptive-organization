# I_acc(w0,w1) by an LP over a DENSE set of effect-cone directions (rays AND interior directions), scipy linprog.
# If R2 is right, adding interior directions cannot raise the value above the ray-only LP.
import numpy as np, itertools, sys
from scipy.optimize import linprog
from rv_err import polygon, effects
def cone_dirs(V,dense=400,rng=np.random.default_rng(3)):
    E=effects(V)   # effect-polytope vertices: every effect is a conv. comb.; cone generated by them
    E=E[np.linalg.norm(E,axis=1)>1e-12]
    # random convex combinations of effect vertices = interior / boundary directions
    W=rng.dirichlet(np.ones(len(E))*0.3,size=dense)@E
    return np.vstack([E,W])
def phi(D,w0,w1):
    a0=D@w0; a1=D@w1; ab=(a0+a1)/2
    with np.errstate(divide='ignore',invalid='ignore'):
        t=lambda a: np.where(a>1e-15,a*np.log2(np.where(a>1e-15,a,1)/np.where(ab>1e-15,ab,1)),0.0)
        return 0.5*t(a0)+0.5*t(a1)
def iacc(D,w0,w1):
    u=np.array([0,0,1.0]); c=-phi(D,w0,w1)
    r=linprog(c,A_eq=D.T,b_eq=u,bounds=[(0,None)]*len(D),method="highs")
    return -r.fun
def total(V,D,enc,k):
    strings=list(itertools.product((0,1),repeat=k)); tot=0
    for j in range(k):
        w0=np.mean([V[e] for s,e in zip(strings,enc) if s[j]==0],0); w1=np.mean([V[e] for s,e in zip(strings,enc) if s[j]==1],0)
        tot+=iacc(D,w0,w1)
    return tot
if __name__=="__main__":
    for n in (4,5,6,8):
        V=polygon(n); D=cone_dirs(V); Donly=effects(V); Donly=Donly[np.linalg.norm(Donly,axis=1)>1e-12]
        best=(0,None)
        for enc in itertools.product(range(n),repeat=3):   # k=2, enc[0]=0 by symmetry
            enc=(0,)+enc; t=total(V,Donly,enc,2)
            if t>best[0]+1e-9: best=(t,enc)
        dense=total(V,D,best[1],2)
        print(f"n={n}: k=2 exhaustive (LP over effect-polytope vertices) {best[0]:.6f} enc {best[1]}; same enc with +400 interior dirs {dense:.6f}",flush=True)
